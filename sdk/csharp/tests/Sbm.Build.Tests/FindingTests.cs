using Sbm.Analyzers;
using RuleSet = Sbm.Analyzers.RuleSet;

namespace Sbm.Build.Tests;

public class FindingTests
{
    [Fact]
    public void A_forbidden_api_stops_before_the_build()
    {
        using var bot = new Workspace().Add(
            "Bot.cs",
            Text.Bot("void M() => Console.WriteLine(1);")
        );

        var result = bot.Build();

        Assert.Contains(result.Analysis.Findings, finding => finding.Rule == "SBM1001");
        Assert.Null(result.Build);
        Assert.Null(result.Program);
    }

    [Fact]
    public void Top_level_statements_are_reported()
    {
        using var bot = new Workspace()
            .Add("Bot.cs", Text.Bot())
            .Add("Program.cs", "Sbm.Sdk.Run<TestBot>();");

        var result = bot.Build();

        var finding = Assert.Single(result.Analysis.Findings);
        Assert.Equal(new Finding("SBM2002", "Program.cs", 1, finding.Message), finding);
        Assert.Null(result.Build);
    }

    [Theory]
    [InlineData("#pragma warning disable SBM1001\n")]
    [InlineData(
        "[System.Diagnostics.CodeAnalysis.SuppressMessage(\"SchachBotManager\", \"SBM1001\")]\n"
    )]
    public void A_suppression_does_not_hide_a_finding(string suppression)
    {
        using var bot = new Workspace().Add(
            "Bot.cs",
            Text.Bot(suppression + "public void M() => Console.WriteLine(1);")
        );

        Assert.Contains(bot.Build().Analysis.Findings, finding => finding.Rule == "SBM1001");
    }

    [Theory]
    [InlineData("Bot.g.cs", "")]
    [InlineData("Bot.cs", "// <auto-generated/>\n")]
    public void Code_that_looks_generated_is_analyzed(string file, string header)
    {
        using var bot = new Workspace().Add(
            file,
            header + Text.Bot("void M() => Console.WriteLine(1);")
        );

        Assert.Contains(bot.Build().Analysis.Findings, finding => finding.Rule == "SBM1001");
    }

    [Fact]
    public void A_line_directive_does_not_move_a_finding()
    {
        using var bot = new Workspace().Add(
            "Bot.cs",
            Text.Bot("#line 1 \"Other.cs\"\nvoid M() => Console.WriteLine(1);")
        );

        var finding = Assert.Single(bot.Build().Analysis.Findings);
        Assert.Equal(("Bot.cs", 7), (finding.File, finding.Line));
    }

    [Fact]
    public void Invalid_utf8_is_reported()
    {
        using var bot = new Workspace()
            .Add("Bot.cs", Text.Bot())
            .Add("Latin1.cs", [0x2F, 0x2F, 0xE4, 0x0A]);

        var result = bot.Build();

        Assert.Equal(
            [new Finding("SBM2006", "Latin1.cs", null, "not valid UTF-8")],
            result.Analysis.Findings
        );
    }

    [Theory]
    [InlineData("Missing", "is not a class of the bot")]
    [InlineData("Helper", "does not derive from Sbm.Bot")]
    [InlineData("Shape", "is not a class")]
    [InlineData("AbstractBot", "must not be abstract or static")]
    [InlineData("HiddenBot", "has no public constructor without parameters")]
    [InlineData("SeededBot", "has no public constructor without parameters")]
    [InlineData("RequiredBot", "must not have required members")]
    public void A_wrong_bot_class_is_reported(string entry, string problem)
    {
        const string members = """
            public class Helper { }
            public struct Shape { }
            public abstract class AbstractBot : Sbm.Bot { }
            public sealed class HiddenBot : TestBot { private HiddenBot() { } }
            public sealed class SeededBot : TestBot { public SeededBot(int seed) { } }
            public sealed class RequiredBot : TestBot { public required int Depth { get; init; } }
            """;
        using var bot = new Workspace().Add(
            "Bot.cs",
            Text.Bot().Replace("sealed ", "", StringComparison.Ordinal) + "\n" + members
        );

        var result = bot.Build(entry);

        var finding = Assert.Single(result.Build!.Findings);
        Assert.Equal("SBM2001", finding.Rule);
        Assert.Equal($"the bot class '{entry}' {problem}", finding.Message);
        Assert.Null(result.Program);
    }

    [Fact]
    public void A_reference_outside_the_whitelist_is_reported()
    {
        var text = File.ReadAllText(
            Repository.Path("sdk/csharp/src/Sbm.Analyzers/csharp_rules.txt")
        );
        var rules = RuleSet.Parse(
            text.Replace("assembly System.Collections\n", "", StringComparison.Ordinal)
        );
        using var bot = new Workspace().Add(
            "Bot.cs",
            Text.Bot("int M() => new Dictionary<int, int>().Count;")
        );

        var result = bot.Build("TestBot", rules);

        Assert.Equal(
            [
                new Finding(
                    "SBM2003",
                    "",
                    null,
                    "the reference to 'System.Collections' is not allowed"
                ),
            ],
            result.Build!.Findings
        );
        Assert.Null(result.Program);
    }

    [Fact]
    public void Findings_are_limited()
    {
        var members = string.Concat(
            Enumerable.Range(0, 150).Select(i => $"void M{i}() => Console.Beep();\n")
        );
        using var bot = new Workspace().Add("Bot.cs", Text.Bot(members));

        var analysis = bot.Build().Analysis;

        Assert.True(analysis.Truncated);
        Assert.Equal(Section.Limit, analysis.Findings.Count);
    }
}
