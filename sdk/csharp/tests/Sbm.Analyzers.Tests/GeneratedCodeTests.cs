namespace Sbm.Analyzers.Tests;

public class GeneratedCodeTests
{
    private const string Forbidden = """
        public static class Helper
        {
            public static string Read() => System.IO.File.ReadAllText("/etc/passwd");
        }
        """;

    [Theory]
    [InlineData("Helper.g.cs", "")]
    [InlineData("Helper.Designer.cs", "")]
    [InlineData("Helper.cs", "// <auto-generated/>\n")]
    [InlineData("Helper.cs", "// <autogenerated />\n")]
    public void The_ide_skips_code_that_looks_generated(string path, string header)
    {
        var findings = Analysis.Run(("Bot.cs", Analysis.Bot("")), (path, header + Forbidden));

        Assert.Empty(findings);
    }

    [Theory]
    [InlineData("Helper.g.cs", "")]
    [InlineData("Helper.Designer.cs", "")]
    [InlineData("Helper.cs", "// <auto-generated/>\n")]
    [InlineData("Helper.cs", "// <autogenerated />\n")]
    public void The_server_analyzes_code_that_looks_generated(string path, string header)
    {
        var findings = Analysis.RunAsServer(
            ("Bot.cs", Analysis.Bot("")),
            (path, header + Forbidden)
        );

        Assert.Contains(findings, finding => finding.Rule == "SBM1001" && finding.File == path);
    }
}
